#!/usr/bin/env python3
"""Generate the LaTeX results tables of the LRE paper from the evaluation outputs.

Each table is written to <paper>/tables/<name>.tex and \\input from main_lre.tex,
so numbers are never copied by hand. Missing cells print as "--".

Usage:
    python code/paper_tables.py [--paper /mnt/kesha/armen-paper]
"""

