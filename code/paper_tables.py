def human_summary(film, tgt="English"):
    base = EVAL / "human-eval" / film
    p = base / f"Russian-{tgt}" / "summary_human_gpt-5.2.json"
    if not p.exists():
        p = base / "summary_human_gpt-5.2.json"
    pm = json.loads(p.read_text())["per_method"] if p.exists() else {}
    if "meme-list" in pm:  # older session naming
        pm.setdefault("list", pm["meme-list"])
    return pm


def table_pilot(label, caption):
    auto, human = summary("ivan-vas", "gpt-5.2"), human_summary("ivan-vas")
    head = ["Evaluation"] + [f"\\rotatebox{{60}}{{{h}}}" for _, h in PILOT]
    keys = [m for m, _ in PILOT]
    rows = [stacked("Automatic", [auto.get(m) for m in keys], keys), stacked("Human", [human.get(m) for m in keys], keys)]
    return tabular(head, rows, label, caption)


