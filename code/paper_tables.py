def table_stability(models, label, caption):
    """Pooled translation-sampling and evaluator SD per translator, over all English films and methods."""
    rows = []
    for mod in models:
        tr, ev, n = [], [], 0
        for film, _ in FILMS:
            for v in summary(film, mod).values():
                if v.get("num_translations", 0) > 1:
                    tr.append(v["translation_sd"] ** 2); n += 1
                if v.get("pooled_eval_run_sd") is not None:
                    ev.append(v["pooled_eval_run_sd"] ** 2)
        if not tr:
            continue
        rows.append(f"{MODEL_NAME[mod]} & {math.sqrt(sum(tr) / len(tr)):.3f} & {math.sqrt(sum(ev) / len(ev)):.3f} & {n} \\\\")
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{lrrr}}\n\\toprule\n"
            f"Translator & Translation SD & Evaluator SD & Method$\\times$film cells \\\\\n\\midrule\n"
            + "\n".join(rows) + f"\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_difficulty(label, caption):
    sig = [("sentinel", "Sentinel-src"), ("cometkiwi-gpt-5.2-zero-1", "CometKiwi"), ("llm-gpt-5-mini", "LLM rating")]
    rows = []
    for film, title in FILMS:
        cells, n = [], None
        for s, _ in sig:
            f = EVAL / "difficulty" / film / f"{s}.json"
            if f.exists():
                d = json.loads(f.read_text())
                n = d["n_meme_entries"], d["n_entries"]
                cells += [f"{d['auroc']:.2f}", f"{d['recall_at_k']:.2f}"]
            else:
                cells += ["--", "--"]
        if n:
            rows.append(f"{title} ({n[0]}/{n[1]}) & " + " & ".join(cells) + r" \\")
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{{h}}}" for _, h in sig)
    sub = " & ".join("AUROC & R@K" for _ in sig)
    rules = "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(sig)))
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{l{'rr' * len(sig)}}}\n\\toprule\n"
            f" & {head} \\\\\n{rules}\nFilm (meme / all entries) & {sub} \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


