def table_prompt_versions(label, caption):
    """Agreement of the main evaluator with the human ranking of conditions, original vs revised Meme-MQM prompt,
    on the very translations the human judged (as in table_metrics)."""
    judge, prompts = JUDGE["English"], ("mqm-memes", "mqm-memes-v2")
    models = ("gpt-6-sol", "claude-opus-5-5")
    rows, rhos = [], {(m, q): [] for m in models for q in prompts}
    for film, title in FILMS:
        cells = []
        for model in models:
            hp = EVAL / "human-eval" / "gpt-6-opus-5.5" / film / f"summary_human_{model}.json"
            hpm = json.loads(hp.read_text())["per_method"] if hp.exists() else {}
            human = {m: v["mean_major_equiv_per_unit"] for m, v in hpm.items()}
            for q in prompts:
                d = EVAL / "llm-eval" / film / "Russian-English" / f"{model}-by-{judge}" / q
                f = next((d / n for n in ("merged_summary.json", "aggregated_summary.json") if (d / n).exists()), None)
                ms = json.loads(f.read_text())["per_method"] if f else {}
                auto = {}
                for m, v in ms.items():
                    pt = v.get("per_translation", {})
                    vals = [pt[r]["mean_major_equiv_per_unit"] for r in hpm.get(m, {}).get("per_translation", {}) if r in pt]
                    if vals:
                        auto[m] = sum(vals) / len(vals)
                common = sorted(set(human) & set(auto))
                rho = spearman([human[c] for c in common], [auto[c] for c in common]) if len(common) >= 4 else float("nan")
                if rho == rho:
                    rhos[(model, q)].append(rho)
                cells.append(f"{rho:+.2f}" if rho == rho else "--")
        cells = bold_max(cells[:2]) + bold_max(cells[2:])
        rows.append(f"{title} & " + " & ".join(cells) + r" \\")
    mean = [f"{sum(v) / len(v):+.2f}" if v else "--" for v in rhos.values()]
    mean = " & ".join(bold_max(mean[:2]) + bold_max(mean[2:]))
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{{MODEL_NAME[m]}}}" for m in models)
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{lrrrr}}\n\\toprule\n"
            f" & {head} \\\\\n\\cmidrule(lr){{2-3}}\\cmidrule(lr){{4-5}}\n"
            f"Film & Original & Revised & Original & Revised \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\midrule\nMean & {mean} \\\\\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


