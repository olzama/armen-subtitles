#!/usr/bin/env python3
"""Generate the LaTeX results tables of the LRE paper from the evaluation outputs.

Each table is written to <paper>/tables/<name>.tex and \\input from main_lre.tex,
so numbers are never copied by hand. Missing cells print as "--".

Usage:
    python code/paper_tables.py [--paper /mnt/kesha/armen-paper]
"""

import argparse
import json
import math
from pathlib import Path

EVAL = Path("experiments/films/output/eval")
FILMS = [("ivan-vas", "Ivan Vasilievich"), ("diamond-arm", "Diamond Arm"), ("gentelmen", "Gentlemen of Fortune"),
         ("carnival-night", "Carnival Night"), ("pokrov-gate", "Pokrov Gates")]
METHODS = [("zero", "zero"), ("characters", "characters"), ("list", "meme list"),
           ("list-analysis", "list+analysis"), ("meme-search", "meme-search"), ("given", "given trans.")]
JUDGE = {"English": "gpt-5-mini", "Galician": "gpt-5.4-mini", "Spanish": "gpt-5.4-mini"}
MODEL_NAME = {"gpt-5.4-mini": "GPT-5.4-mini", "gpt-5.2": "GPT-5.2", "gpt-6-sol": "GPT-6 Sol",
              "claude-opus-5-5": "Opus 5.5"}


def summary(film, model, tgt="English"):
    d = EVAL / "llm-eval" / film / f"Russian-{tgt}" / f"{model}-by-{JUDGE[tgt]}" / "mqm-memes"
    for name in ("merged_summary.json", "aggregated_summary.json"):
        if (d / name).exists():
            return json.loads((d / name).read_text())["per_method"]
    return {}


def method_key(per_method, m, tgt):
    # Galician runs use the "-lang" variants as the main condition.
    if tgt == "Galician" and m != "meme-search" and f"{m}-lang" in per_method:
        return f"{m}-lang"
    return m


def cell(v, ci=True):
    if not v:
        return "--"
    mean = f"{v['mean_major_equiv_per_unit']:.2f}"
    if ci and v.get("num_translations", 0) > 1:
        return f"{mean}\\,{{\\scriptsize$\\pm${v['ci_95_half_width']:.2f}}}"
    return mean


def write(paper, name, body):
    out = paper / "tables" / f"{name}.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("% Generated by code/paper_tables.py; do not edit by hand.\n" + body)
    print("wrote", out)


def table_films(model, label, caption, tgt="English"):
    rows = []
    for film, title in FILMS:
        s = summary(film, model, tgt)
        if not s:
            continue
        rows.append(f"{title} & " + " & ".join(cell(s.get(method_key(s, m, tgt))) for m, _ in METHODS) + r" \\")
    head = " & ".join(h for _, h in METHODS)
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{adjustbox}}{{max width=\\textwidth}}\n"
            f"\\begin{{tabular}}{{l{'r' * len(METHODS)}}}\n\\toprule\nFilm & {head} \\\\\n\\midrule\n"
            + "\n".join(rows) + f"\n\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n"
            f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_models(film, models, label, caption, tgt="English"):
    sums = {m: summary(film, m, tgt) for m in models}
    rows = []
    for m, h in METHODS:
        rows.append(f"{h} & " + " & ".join(cell(sums[mod].get(method_key(sums[mod], m, tgt))) for mod in models) + r" \\")
    t = [" & ".join(str(max((v.get("num_translations", 0) for v in sums[mod].values()), default=0)) for mod in models)]
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{l{'r' * len(models)}}}\n\\toprule\n"
            f"Method & " + " & ".join(MODEL_NAME[m] for m in models) + " \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\midrule\nTranslations per method (max) & {t[0]} \\\\\n\\bottomrule\n\\end{{tabular}}\n"
            f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


PILOT = [("zero", "zero"), ("summary", "summary"), ("characters", "characters"), ("narratives", "narratives"),
         ("intertext", "intertext"), ("examples", "examples"), ("list", "meme list"), ("list-analysis", "list+analysis"),
         ("meme-search", "meme-search"), ("given", "given trans."), ("noise", "added noise")]


def table_pilot(label, caption):
    s = summary("ivan-vas", "gpt-5.2")
    rows = [f"{h} & {cell(s.get(m))} \\\\" for m, h in PILOT]
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{lr}}\n\\toprule\nCondition & Meme-MQM \\\\\n\\midrule\n"
            + "\n".join(rows) + f"\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_stability(models, label, caption):
    """Pooled translation-sampling and evaluator SD per translator, over all English films and methods."""
    rows = []
    for mod in models:
        tr, ev, n = [], [], 0
        for film, _ in FILMS:
            for v in summary(film, mod).values():
                if v.get("num_translations", 0) > 1:
                    tr.append(v["translation_sd"] ** 2); n += 1
                if v.get("pooled_eval_run_sd") is not None:
                    ev.append(v["pooled_eval_run_sd"] ** 2)
        if not tr:
            continue
        rows.append(f"{MODEL_NAME[mod]} & {math.sqrt(sum(tr) / len(tr)):.3f} & {math.sqrt(sum(ev) / len(ev)):.3f} & {n} \\\\")
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{lrrr}}\n\\toprule\n"
            f"Translator & Translation SD & Evaluator SD & Method$\\times$film cells \\\\\n\\midrule\n"
            + "\n".join(rows) + f"\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_difficulty(label, caption):
    sig = [("sentinel", "Sentinel-src"), ("cometkiwi-gpt-5.2-zero-1", "CometKiwi"), ("llm-gpt-5-mini", "LLM rating")]
    rows = []
    for film, title in FILMS:
        cells, n = [], None
        for s, _ in sig:
            f = EVAL / "difficulty" / film / f"{s}.json"
            if f.exists():
                d = json.loads(f.read_text())
                n = d["n_meme_entries"], d["n_entries"]
                cells += [f"{d['auroc']:.2f}", f"{d['recall_at_k']:.2f}"]
            else:
                cells += ["--", "--"]
        if n:
            rows.append(f"{title} ({n[0]}/{n[1]}) & " + " & ".join(cells) + r" \\")
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{{h}}}" for _, h in sig)
    sub = " & ".join("AUROC & R@K" for _ in sig)
    rules = "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(sig)))
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{l{'rr' * len(sig)}}}\n\\toprule\n"
            f" & {head} \\\\\n{rules}\nFilm (meme / all entries) & {sub} \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_coverage(label, caption):
    f = EVAL / "difficulty" / "meme_search_coverage.json"
    d = json.loads(f.read_text()) if f.exists() else {}
    models = [m for m in ("gpt-5.2", "gpt-6-sol") if m in d]
    rows = []
    for film, title in FILMS:
        cells = []
        for m in models:
            v = d[m].get(film)
            cells += [f"{v['found']}/{v['memes']}", f"{v.get('analysis_correct', '--')}/{v['memes']}"] if v else ["--", "--"]
        rows.append(f"{title} & " + " & ".join(cells) + r" \\")
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{{MODEL_NAME[m]}}}" for m in models)
    rules = "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(models)))
    sub = " & ".join("Found & Analyzed" for _ in models)
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{l{'rr' * len(models)}}}\n\\toprule\n"
            f" & {head} \\\\\n{rules}\nFilm & {sub} \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_counts(label, caption):
    tr_root = Path("experiments/films/output/translations")
    rows = []
    for tgt in ("English", "Galician", "Spanish"):
        for model in ("gpt-6-sol", "claude-opus-5-5", "gpt-5.2", "gpt-5.4-mini"):
            films, n_tr, n_ev, memes = 0, 0, 0, 0
            for film, _ in FILMS:
                d = tr_root / film / f"Russian-{tgt}" / model
                files = list(d.glob("*/translations/translation-*.txt")) if d.exists() else []
                if not files:
                    continue
                films += 1
                n_tr += len(files)
                memes += len(json.loads(Path(f"experiments/films/data/{film}/reference.json").read_text())["items"])
                ev = EVAL / "llm-eval" / film / f"Russian-{tgt}" / f"{model}-by-{JUDGE[tgt]}" / "mqm-memes"
                n_ev += len(list(ev.glob("*/run_*_eval_*.json"))) if ev.exists() else 0
            if films:
                rows.append(f"Russian$\\to${tgt} & {MODEL_NAME[model]} & {films} & {memes} & {n_tr} & {n_ev} \\\\")
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{llrrrr}}\n\\toprule\n"
            f"Language pair & Translator & Films & Memes & Translations & Evaluation runs \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(xs):
        j = i
        while j + 1 < len(xs) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2
        i = j + 1
    return r


def spearman(a, b):
    ra, rb = ranks(a), ranks(b)
    n = len(a)
    ma, mb = sum(ra) / n, sum(rb) / n
    cov = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    va = sum((x - ma) ** 2 for x in ra) ** 0.5
    vb = sum((y - mb) ** 2 for y in rb) ** 0.5
    return cov / (va * vb) if va and vb else float("nan")


def table_metrics(label, caption):
    """Spearman correlation, across conditions, between human Meme-MQM and each automatic metric
    (GPT-5.2 translations). Metrics are oriented so that positive = agrees with the human ranking."""
    groups = [("ivan-vas", "English", "Ivan Vasilievich"), ("diamond-arm", "English", "Diamond Arm"),
              ("gentelmen", "English", "Gentlemen of Fortune"), ("carnival-night", "English", "Carnival Night"),
              ("ivan-vas", "Galician", "Ivan Vasilievich (Galician)")]
    metrics = [("cometkiwi", "CometKiwi", -1), ("xcomet", "xCOMET", -1), ("metricx", "MetricX", 1),
               ("wf", "LLM whole-text", 1), ("meme", "Meme-MQM (auto)", 1)]
    rows, per_metric = [], {m: [] for m, _, _ in metrics}
    for film, tgt, title in groups:
        hp = EVAL / "human-eval" / film / (f"Russian-{tgt}" if (EVAL / "human-eval" / film / f"Russian-{tgt}").exists() else "") / "summary_human_gpt-5.2.json"
        if not hp.exists():
            continue
        human = {m: v["mean_major_equiv_per_unit"] for m, v in json.loads(hp.read_text())["per_method"].items()}
        auto = {"meme": {m: v["mean_major_equiv_per_unit"] for m, v in summary(film, "gpt-5.2", tgt).items()}}
        for m, _, _ in metrics[:3]:
            f = EVAL / "comet-eval" / film / f"Russian-{tgt}" / "gpt-5.2" / f"aligned_scores_{m}.json"
            auto[m] = {k: v["mean_score"] for k, v in json.loads(f.read_text())["methods"].items()} if f.exists() else {}
        wf_root = EVAL / "llm-eval" / film / f"Russian-{tgt}" / "gpt-5.2-by-gpt-5.4" / "mqm-wholefile"
        auto["wf"] = {}
        if wf_root.exists():
            for d in wf_root.iterdir():
                runs = list(d.glob("run_*_eval_*.json")) if d.is_dir() else []
                if runs:
                    auto["wf"][d.name] = sum(json.loads(r.read_text())["summary"]["major_equiv_per_unit"] for r in runs) / len(runs)
        cells, n = [], None
        for m, _, sign in metrics:
            common = sorted(set(human) & set(auto[m]))
            if len(common) < 4:
                cells.append("--"); continue
            rho = spearman([human[c] for c in common], [sign * auto[m][c] for c in common])
            per_metric[m].append(rho); n = len(common)
            cells.append(f"{rho:+.2f}")
        rows.append(f"{title} & {n or '--'} & " + " & ".join(cells) + r" \\")
    mean = " & ".join(f"{sum(v) / len(v):+.2f}" if v else "--" for v in per_metric.values())
    head = " & ".join(h for _, h, _ in metrics)
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{adjustbox}}{{max width=\\textwidth}}\n"
            f"\\begin{{tabular}}{{lr{'r' * len(metrics)}}}\n\\toprule\nFilm & $N$ & {head} \\\\\n\\midrule\n"
            + "\n".join(rows) + f"\n\\midrule\nMean & & {mean} \\\\\n\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n"
            f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_judges(label, caption):
    """Agreement between the GPT-5-mini and Claude Haiku 5.5 evaluators on GPT-6 Sol translations."""
    rows, rhos = [], []
    for film, title in FILMS:
        a = summary(film, "gpt-6-sol")
        d = EVAL / "llm-eval" / film / "Russian-English" / "gpt-6-sol-by-claude-haiku-5-5" / "mqm-memes"
        b = {}
        for name in ("merged_summary.json", "aggregated_summary.json"):
            if (d / name).exists():
                b = json.loads((d / name).read_text())["per_method"]; break
        common = [m for m, _ in METHODS if m in a and m in b]
        if len(common) < 4:
            continue
        x = [a[m]["mean_major_equiv_per_unit"] for m in common]
        y = [b[m]["mean_major_equiv_per_unit"] for m in common]
        rho = spearman(x, y); rhos.append(rho)
        best = lambda v: min(common, key=lambda m: v[common.index(m)])
        rows.append(f"{title} & {len(common)} & {rho:+.2f} & {dict(METHODS)[best(x)]} & {dict(METHODS)[best(y)]} \\\\")
    mean = f"{sum(rhos) / len(rhos):+.2f}" if rhos else "--"
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{tabular}}{{lrrll}}\n\\toprule\n"
            f"Film & Conditions & Spearman $\\rho$ & Best (GPT-5-mini) & Best (Haiku 5.5) \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\midrule\nMean & & {mean} & & \\\\\n\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def table_human_current(label, caption):
    """Human Meme-MQM on GPT-6 Sol and Opus 5.5 (one translation per condition), with the Spearman
    correlation between the human and the automatic ranking of conditions for each film."""
    blocks = []
    for model in ("gpt-6-sol", "claude-opus-5-5"):
        rows = []
        for film, title in FILMS:
            p = EVAL / "human-eval" / "gpt-6-opus-5.5" / film / f"summary_human_{model}.json"
            if not p.exists():
                continue
            h = json.loads(p.read_text())["per_method"]
            a = summary(film, model)
            common = [m for m, _ in METHODS if m in h and m in a]
            rho = spearman([h[m]["mean_major_equiv_per_unit"] for m in common],
                           [a[m]["mean_major_equiv_per_unit"] for m in common])
            rows.append(f"{title} & " + " & ".join(cell(h.get(m), ci=False) for m, _ in METHODS) + f" & {rho:+.2f} \\\\")
        blocks.append(f"\\multicolumn{{{len(METHODS) + 2}}}{{l}}{{\\textit{{{MODEL_NAME[model]}}}}} \\\\\n" + "\n".join(rows))
    head = " & ".join(h for _, h in METHODS)
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{adjustbox}}{{max width=\\textwidth}}\n"
            f"\\begin{{tabular}}{{l{'r' * len(METHODS)}r}}\n\\toprule\nFilm & {head} & $\\rho$ \\\\\n\\midrule\n"
            + "\n\\midrule\n".join(blocks) + f"\n\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n"
            f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", type=Path, default=Path("/mnt/kesha/armen-paper"))
    a = ap.parse_args()
    note = ("MQM adapted score (major-error equivalents per meme; lower is better), mean over translations "
            "and evaluation runs, with the 95\\% method-level confidence interval.")
    write(a.paper, "strong-films", table_films(
        "gpt-6-sol", "tab:strong-films",
        f"GPT-6 Sol, Russian$\\to$English, three translations per condition, evaluator GPT-5-mini. {note}"))
    write(a.paper, "models-ivan-vas", table_models(
        "ivan-vas", ["gpt-5.2", "gpt-6-sol", "claude-opus-5-5"], "tab:models-ivan-vas",
        f"\\textit{{Ivan Vasilievich}} under three translators, same evaluator (GPT-5-mini). {note} "
        "No interval is shown where a condition has a single translation."))
    write(a.paper, "opus-films", table_films(
        "claude-opus-5-5", "tab:opus-films",
        f"Claude Opus 5.5, Russian$\\to$English, one translation per condition (no \\textit{{meme-search}}: the model was run without tools), evaluator GPT-5-mini. "
        "MQM adapted score (major-error equivalents per meme; lower is better); with one translation per condition, no method-level interval is shown."))
    write(a.paper, "weak-films", table_films(
        "gpt-5.2", "tab:weak-films",
        f"GPT-5.2, Russian$\\to$English, evaluator GPT-5-mini. {note}"))
    write(a.paper, "model-scale", table_models(
        "diamond-arm", ["gpt-5.2", "gpt-5.4-mini"], "tab:model-scale",
        f"\\textit{{Diamond Arm}} under GPT-5.2 and the smaller GPT-5.4-mini, same evaluator (GPT-5-mini). {note} "
        "GPT-5.4-mini was run only on the conditions shown."))
    write(a.paper, "galician", table_models(
        "ivan-vas", ["gpt-5.2", "gpt-6-sol"], "tab:galician",
        f"\\textit{{Ivan Vasilievich}}, Russian$\\to$Galician (conditions with the Galician language addendum), "
        f"evaluator GPT-5.4-mini. {note}", tgt="Galician"))
    write(a.paper, "pilot", table_pilot(
        "tab:pilot",
        f"Pilot: all eleven conditions on \\textit{{Ivan Vasilievich}}, GPT-5.2, Russian$\\to$English, evaluator GPT-5-mini. {note}"))
    write(a.paper, "spanish", table_models(
        "ivan-vas", ["gpt-5.2"], "tab:spanish",
        f"\\textit{{Ivan Vasilievich}}, Russian$\\to$Spanish, GPT-5.2, evaluator GPT-5.4-mini (automatic evaluation only). {note}",
        tgt="Spanish"))
    write(a.paper, "stability", table_stability(
        ["gpt-5.2", "gpt-6-sol"], "tab:stability",
        "Pooled standard deviation of the Meme-MQM score across translations of the same condition "
        "(translation sampling) and across repeated evaluation runs of the same translation (evaluator), "
        "over all English films and conditions with more than one translation."))
    write(a.paper, "counts", table_counts(
        "tab:counts",
        "Released translations and automatic evaluation runs per language pair and translator. Memes are counted "
        "once per film; each translation is a full subtitle file; each evaluation run scores all memes of one translation."))
    write(a.paper, "metrics", table_metrics(
        "tab:metrics-human",
        "Spearman correlation, across translation conditions, between human Meme-MQM scores and each automatic "
        "metric, for GPT-5.2 translations (the translations with human evaluation). Metrics are oriented so that a "
        "positive value means agreement with the human ranking of conditions. $N$: conditions with both scores. "
        "CometKiwi, xCOMET and MetricX are reference-free and time-code aligned; the LLM whole-text judge is GPT-5.4."))
    write(a.paper, "human-current", table_human_current(
        "tab:human-current",
        "Human Meme-MQM (major-error equivalents per meme; lower is better) for the current translators, "
        "Russian$\\to$English, one translation per condition, one evaluator. $\\rho$: Spearman correlation, across "
        "conditions, between the human scores and the automatic Meme-MQM scores (GPT-5-mini) of the same film and translator."))
    write(a.paper, "judges", table_judges(
        "tab:judges",
        "Agreement between two Meme-MQM evaluators from different model families (GPT-5-mini and Claude Haiku 5.5) "
        "on the GPT-6 Sol translations: Spearman correlation between their rankings of the translation conditions, "
        "and the condition each ranks best."))
    write(a.paper, "coverage", table_coverage(
        "tab:coverage",
        "The translator's own web search and analysis (\\textit{meme-search}) against the audience-selected memes. "
        "Found: memes the model's list discusses, in any language or wording. Analyzed: memes for which the model's "
        "notes identify the same essential mechanism or pitfall as the approved analysis. Both judged by GPT-5.4."))
    write(a.paper, "difficulty", table_difficulty(
        "tab:difficulty",
        "How well off-the-shelf difficulty signals find the meme entries among all subtitle entries of a film. "
        "AUROC: probability that a meme entry is ranked harder than a non-meme entry (0.5 = chance). "
        "R@K: share of meme entries among the $K$ entries ranked hardest, $K$ = number of meme entries. "
        "Sentinel-src-25 scores the source alone; CometKiwi scores a zero-shot GPT-5.2 translation; "
        "the LLM rating asks GPT-5-mini to rate each entry's translation difficulty."))


if __name__ == "__main__":
    main()
