import json
import re
import math
from pathlib import Path

# Paths in this repository, or in the released dataset (eval/, translations/, data/ at the top level).
RELEASE = not Path("experiments").exists() and Path("eval").exists()
EVAL = Path("eval") if RELEASE else Path("experiments/films/output/eval")
TRANSLATIONS = Path("translations") if RELEASE else Path("experiments/films/output/translations")
DATA = Path("data") if RELEASE else Path("experiments/films/data")
LANG_CODE = {"English": "eng", "Galician": "glg", "Spanish": "spa"}
FILMS = [("ivan-vas", "Ivan Vasilievich"), ("diamond-arm", "Diamond Arm"), ("gentelmen", "Gentlemen of Fortune"),
         ("carnival-night", "Carnival Night"), ("pokrov-gate", "Pokrov Gates")]
METHODS = [("zero", "zero"), ("characters", "characters"), ("list", "meme list"),
           ("list-analysis", "list+analysis"), ("meme-search", "meme-search"), ("given", "given trans.")]
# Main Meme-MQM evaluator, and the earlier GPT evaluator kept for comparison.
JUDGE = {"English": "claude-sonnet-5-5", "Galician": "claude-sonnet-5-5", "Spanish": "claude-sonnet-5-5"}
GPT_JUDGE = {"English": "gpt-5-mini", "Galician": "gpt-5.4-mini", "Spanish": "gpt-5.4-mini"}
# Meme-MQM prompt per evaluator: the Claude evaluators use the revised prompt (v2); the GPT evaluators
# were not re-run and keep the original prompt.
def meme_prompt(judge):
    return "mqm-memes-v2" if judge.startswith("claude") else "mqm-memes"
MODEL_NAME = {"gpt-5.4-mini": "GPT-5.4-mini", "gpt-5.2": "GPT-5.2", "gpt-6-sol": "GPT-6 Sol",
              "claude-opus-5-5": "Opus 5.5"}


def summary(film, model, tgt="English", judge=None):
    d = EVAL / "llm-eval" / film / f"Russian-{tgt}" / f"{model}-by-{judge or JUDGE[tgt]}" / meme_prompt(judge or JUDGE[tgt])
    for name in ("merged_summary.json", "aggregated_summary.json"):
        if (d / name).exists():
            return json.loads((d / name).read_text())["per_method"]
    return {}


def method_key(per_method, m, tgt):
    # Galician runs use the "-lang" variants as the main condition.
    if tgt == "Galician" and m != "meme-search" and f"{m}-lang" in per_method:
        return f"{m}-lang"
    return m


def cell(v, ci=True):
    if not v:
        return "--"
    mean = f"{v['mean_major_equiv_per_unit']:.2f}"
    if ci and v.get("num_translations", 0) > 1:
        return f"{mean}\\,{{\\scriptsize$\\pm${v['ci_95_half_width']:.2f}}}"
    return mean


def best_cells(vals, keys, ci=True):
    """Cells for one row of conditions; the best (lowest) score among the conditions other than the approved
    references (given) is in bold, ties included."""
    def mean(v):
        return f"{v['mean_major_equiv_per_unit']:.2f}" if v else None
    cand = [mean(v) for v, k in zip(vals, keys) if v and not k.startswith("given")]
    best = min(cand, key=float) if cand else None
    out = []
    for v, k in zip(vals, keys):
        c = cell(v, ci)
        if best is not None and mean(v) == best and not k.startswith("given"):
            c = c.replace(best, f"\\textbf{{{best}}}", 1)
        out.append(c)
    return out


def bold_max(strs):
    """Bold the largest of a row of signed numbers (strings such as "+0.81"; "--" ignored), ties included."""
    nums = [float(x) for x in strs if x not in ("--", "")]
    if not nums:
        return strs
    top = max(nums)
    return [f"\\textbf{{{x}}}" if x not in ("--", "") and float(x) == top else x for x in strs]


def write(paper, name, body):
    out = paper / "tables" / f"{name}.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    # Every table spans the text width, so that its caption does too.
    # \fittable (defined in the paper) stretches a narrow table and scales down a wide one.
    body = re.sub(r"\\begin\{tabular\*?\}(?:\{\\textwidth\}\{@\{\\extracolsep\{\\fill\}\}([^}]*)\}|\{([^}]*)\})(.*?)\\end\{tabular\*?\}",
                  lambda m: "\\fittable{" + (m.group(1) or m.group(2)) + "}{" + m.group(3) + "}", body, flags=re.S)
    body = re.sub(r"\\begin\{adjustbox\}\{max width=\\textwidth\}\n(\\fittable.*?\})\n\\end\{adjustbox\}\n", r"\1\n", body, flags=re.S)
    if "\\textbf" in body:  # say what the bold marks
        what = (" Bold: the closest agreement with the human ranking in each row." if name.startswith("metrics")
                else " Bold: the closer agreement with the human ranking for each translator." if name == "prompt-versions"
                else " Bold: the best condition other than the approved references (given trans.), in each row.")
        body = body.replace("}\n\\label{", what + "}\n\\label{", 1)
    out.write_text("% Generated by code/paper_tables.py; do not edit by hand.\n" + body)
    print("wrote", out)


def tabular(head, rows, label, caption, align=None):
    """A full-width booktabs table: head is a list of column titles, rows a list of row strings or "\\midrule"."""
    align = align or "l" + "r" * (len(head) - 1)
    return (f"\\begin{{table}}[ht]\n\\centering\n\\small\n\\begin{{adjustbox}}{{max width=\\textwidth}}\n"
            f"\\begin{{tabular*}}{{\\textwidth}}{{@{{\\extracolsep{{\\fill}}}}{align}}}\n\\toprule\n"
            + " & ".join(head) + " \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\bottomrule\n\\end{{tabular*}}\n\\end{{adjustbox}}\n"
            f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")


def stacked(name, vals, keys=None):
    """Two lines per row: the means, then the 95% half-widths in small type under them."""
    means = " & ".join(c.split("\\,")[0] for c in best_cells(vals, keys, ci=False)) if keys else \
        " & ".join(f"{v['mean_major_equiv_per_unit']:.2f}" if v else "--" for v in vals)
    cis = " & ".join(f"{{\\scriptsize$\\pm${v['ci_95_half_width']:.2f}}}" if v and v.get("num_translations", 0) > 1 else ""
                     for v in vals)
    return f"{name} & {means} \\\\\n & {cis} \\\\[2pt]"


def table_films(model, label, caption, tgt="English"):
    rows = []
    for film, title in FILMS:
        s = summary(film, model, tgt)
        if s:
            keys = [method_key(s, m, tgt) for m, _ in METHODS]
            rows.append(f"{title} & " + " & ".join(best_cells([s.get(k) for k in keys], keys)) + r" \\")
    return tabular(["Film"] + [h for _, h in METHODS], rows, label, caption)


def table_models(film, models, label, caption, tgt="English"):
    rows = []
    for mod in models:
        s = summary(film, mod, tgt)
        n = max((v.get("num_translations", 0) for v in s.values()), default=0)
        keys = [method_key(s, m, tgt) for m, _ in METHODS]
        rows.append(f"{MODEL_NAME[mod]} & " + " & ".join(best_cells([s.get(k) for k in keys], keys))
                    + f" & {n} \\\\")
    if "$T$" not in caption:
        caption += " $T$: translations per condition (most)."
    return tabular(["Translator"] + [h for _, h in METHODS] + ["$T$"], rows, label, caption)


